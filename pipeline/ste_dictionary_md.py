#!/usr/bin/env python3
"""Write the project dictionary tables of docs/STE_STYLE_GUIDE.md from pipeline/ste_dictionary.json.

  python3 pipeline/ste_dictionary_md.py --write   # update the guide between the two marker comments
  python3 pipeline/ste_dictionary_md.py --check   # exit 1 if the guide is out of date (used by test_ste_docs.py)

The JSON file is the source. Never edit the generated part of the guide by hand.
"""
import argparse
import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
JSON_PATH = HERE / "ste_dictionary.json"
GUIDE = HERE.parent / "docs" / "STE_STYLE_GUIDE.md"
BEGIN = "<!-- ste-dictionary:begin (generated by pipeline/ste_dictionary_md.py; do not edit by hand) -->"
END = "<!-- ste-dictionary:end -->"


def cell(text: str) -> str:
    return str(text).replace("|", "/").replace("\n", " ").strip()


def render(data: dict) -> str:
    out: list[str] = []
    out.append("### Approved words that this project uses a lot\n")
    out.append("| Word | Part of speech | Meaning | Example |")
    out.append("|---|---|---|---|")
    for word, e in data["approved_words"].items():
        out.append(f"| {cell(word)} | {cell(e['pos'])} | {cell(e['meaning'])} | {cell(e['example'])} |")
    out.append("")
    out.append("### Unapproved words and the words to use instead\n")
    out.append("The column Basis shows where a pair comes from. `sheet` is the reference sheet of the owner. "
               "`ste` is a pair that public STE summaries show. "
               "`project` is a decision of this project. It follows the rule of one word for one meaning. "
               "Use the official ASD-STE100 dictionary to settle a doubt.\n")
    out.append("| Unapproved | Use | Basis | Note |")
    out.append("|---|---|---|---|")
    for word, e in data["unapproved"].items():
        alts = " / ".join(e["alternatives"])
        out.append(f"| `{cell(word)}` ({cell(e['pos'])}) | {cell(alts)} | {e['basis']} | {cell(e['note'])} |")
    out.append("")
    out.append("### Technical names\n")
    for cat, items in data["technical_names"].items():
        out.append(f"#### {cat}\n")
        out.append("| Name | Meaning |")
        out.append("|---|---|")
        for term, definition in sorted(items.items(), key=lambda kv: kv[0].lower()):
            out.append(f"| {cell(term)} | {cell(definition)} |")
        out.append("")
    out.append("### Technical verbs\n")
    for cat, items in data["technical_verbs"].items():
        out.append(f"#### {cat}\n")
        out.append("| Verb | Meaning |")
        out.append("|---|---|")
        for term, definition in sorted(items.items(), key=lambda kv: kv[0].lower()):
            out.append(f"| {cell(term)} | {cell(definition)} |")
        out.append("")
    ex = data["allowed_exceptions"]
    out.append("### Allowed exceptions\n")
    out.append("These words end in -ing and are nouns or names. The checker accepts them:\n")
    out.append("```text\n" + ", ".join(ex["ing_words"]) + "\n```\n")
    out.append("These past participles work as adjectives after is, are, was and were. The checker accepts them:\n")
    out.append("```text\n" + ", ".join(ex["participle_adjectives"]) + "\n```\n")
    return "\n".join(out).rstrip() + "\n"


def build(guide_text: str, data: dict) -> str:
    if BEGIN not in guide_text or END not in guide_text:
        raise SystemExit("marker comments not found in " + str(GUIDE))
    head, rest = guide_text.split(BEGIN, 1)
    _, tail = rest.split(END, 1)
    return head + BEGIN + "\n<!-- ste-ignore-start STE-1 -->\n\n" + render(data) + "\n<!-- ste-ignore-end -->\n" + END + tail


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    g = ap.add_mutually_exclusive_group(required=True)
    g.add_argument("--write", action="store_true")
    g.add_argument("--check", action="store_true")
    a = ap.parse_args(argv)
    data = json.loads(JSON_PATH.read_text(encoding="utf-8"))
    old = GUIDE.read_text(encoding="utf-8")
    new = build(old, data)
    if a.check:
        if new != old:
            print("docs/STE_STYLE_GUIDE.md is out of date: run python3 pipeline/ste_dictionary_md.py --write", file=sys.stderr)
            return 1
        print("ok")
        return 0
    GUIDE.write_text(new, encoding="utf-8")
    print("written", GUIDE)
    return 0


if __name__ == "__main__":
    sys.exit(main())
